async function run() {
  await mongoose.connect(MONGO_URI);
  console.log("Connected to MongoDB for catalog balancing...");

  const defaultStore = await Store.findOne({ code: "STR-GUR-101" }) || await Store.findOne();

  // Wipe existing products to guarantee a perfectly clean, balanced 5 products per category
  const deleteResult = await Product.deleteMany({});
  console.log(`Cleared ${deleteResult.deletedCount} old products to ensure clean 5 items per category.`);

  let totalSeeded = 0;

  for (const [slug, items] of Object.entries(BALANCED_CATALOG)) {
    const cat = await Category.findOne({ slug });
    if (!cat) {
      console.warn(`Category ${slug} not found!`);
      continue;
    }

    console.log(`\nSeeding 5 balanced products for: ${cat.name} (${slug})`);

    for (let i = 0; i < items.length; i++) {
      const item = items[i];
      const prodSlug = item.title
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/(^-|-$)/g, "")
        .slice(0, 45) + "-" + (i + 1);

      const discount = item.mrp > item.price ? Math.round(((item.mrp - item.price) / item.mrp) * 100) : 0;

      const p = new Product({
        title: item.title,
        slug: prodSlug,
        category: cat._id,
        storeId: defaultStore._id,
        price: item.price,
        mrp: item.mrp,
        discount,
        unit: item.unit,
        stock: 50 + (i * 12),
        tags: item.tags,
        isAvailable: true,
        isFeatured: i === 0 || i === 1,
        rating: item.rating,
        ratingCount: item.ratingCount,
        images: [{ url: item.image, publicId: "" }],
        sortOrder: i + 1,
      });

      await p.save();
      totalSeeded++;
      console.log(`  ✓ [${i+1}/5] ${item.title} -> ${item.image.slice(0, 60)}...`);
    }
  }

  console.log(`\n===========================================`);
  console.log(`Successfully seeded exactly ${totalSeeded} products (5 per category across all 17 categories)!`);
  console.log(`All products have different, unique images!`);
  console.log(`===========================================\n`);

  await mongoose.disconnect();
}

run().catch(err => {
  console.error("Balance catalog error:", err);
  process.exit(1);
});
